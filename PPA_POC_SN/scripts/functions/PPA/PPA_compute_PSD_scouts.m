function PPA_compute_PSD_scouts(subName, mainDir, varargin)
%% Varargin manager

% Default values
cond = [];
psdName = [];
computeAverage = false;
avgName = '';
for i = 1:2:length(varargin)
    switch varargin{i}
        case 'abilitate', abilitate = varargin{i+1};
        case 'PSDname', psdName = varargin{i+1};
        case 'cond', cond = varargin{i+1};
        case 'scoutsName', scoutsName = varargin{i+1};
        case 'computeAverage', computeAverage = varargin{i+1};
        case 'avgName', avgName = varargin{i+1};
    end
end

if ~abilitate
    sprintf("Funzione PPA_SN_features skipped")
    return
end
% Mandatory
assert(~isempty(cond), 'cond parameter is mandatory for extract_band_relative_powers');
assert(~isempty(psdName), 'PSDname parameter is mandatory for extract_band_relative_powers');
assert(~isempty(scoutsName), 'scoutsName parameter is mandatory for extract_band_relative_powers');
assert(~isempty(computeAverage), 'computeAverage parameter is mandatory for extract_band_relative_powers');

%% Find PSD file, if exists
psdFile = bst_process('CallProcess', 'process_select_files_timefreq', [], [], ...
                'subjectname',   subName, ...
                'condition',     cond, ...
                'tag',           psdName, ...
                'includebad',    0, ...
                'includeintra',  0, ...
                'includecommon', 0, ...
                'outprocesstab', 'no');  % No
if ~isempty(psdFile)
    psdFile(~cellfun(@(c) strncmp(c, [psdName ' '], length(psdName)+1), {psdFile.Comment})) = [];
end
% If empty, compute
if isempty(psdFile)
    fprintf("PSD file non trovato per il soggetto %s, procedo a computarlo\n", subName);
    eegFiles = bst_process('CallProcess', 'process_select_files_matrix', [], [], ...
                'subjectname',   subName, ...
                'condition',     cond, ...
                'tag',           scoutsName, ...
                'includebad',    0, ...
                'includeintra',  0, ...
                'includecommon', 0, ...
                'outprocesstab', 'no');  % No
    eegFiles(~cellfun(@(c) strncmp(c, [scoutsName ' '], length(scoutsName)+1), {eegFiles.Comment})) = [];
    psdFile = bst_process('CallProcess', 'process_psd', eegFiles, [], ...
    'timewindow',  [], ...
    'win_length',  1, ...
    'win_overlap', 50, ...
    'units',       'physical', ...  % Physical: U2/Hz
    'sensortypes', 'EEG', ...
    'win_std',     0, ...
    'edit',        struct(...
         'Comment',         psdName, ...
         'TimeBands',       [], ...
         'Freqs',           [], ...
         'ClusterFuncTime', 'none', ...
         'Measure',         'power', ...
         'Output',          'all', ...
         'SaveKernel',      0));
    psdFile = bst_process('CallProcess', 'process_tf_norm', psdFile, [], ...
        'normalize', 'relative2020', ...  % Relative power (divide by total power)
        'overwrite', 1);
    psdFile = bst_process('CallProcess', 'process_set_comment', psdFile, [], ...
            'tag',           psdName, ...
            'isindex',       1);
end

%% Average
if computeAverage
    % Find file
    avgPSDFile = bst_process('CallProcess', 'process_select_files_timefreq', [], [], ...
                'subjectname',   subName, ...
                'condition',     cond, ...
                'tag',           avgName, ...
                'includebad',    0, ...
                'includeintra',  0, ...
                'includecommon', 0, ...
                'outprocesstab', 'no');  % No
    if isempty(avgPSDFile)
        eegFiles = bst_process('CallProcess', 'process_select_files_matrix', [], [], ...
                'subjectname',   subName, ...
                'condition',     cond, ...
                'tag',           scoutsName, ...
                'includebad',    0, ...
                'includeintra',  0, ...
                'includecommon', 0, ...
                'outprocesstab', 'no');  % No
        eegFiles(~cellfun(@(c) strncmp(c, [scoutsName ' '], length(scoutsName)+1), {eegFiles.Comment})) = [];
        avgPSDFile = bst_process('CallProcess', 'process_psd', eegFiles, [], ...
        'timewindow',  [], ...
        'win_length',  1, ...
        'win_overlap', 50, ...
        'units',       'physical', ...  % Physical: U2/Hz
        'sensortypes', 'EEG', ...
        'win_std',     0, ...
        'edit',        struct(...
             'Comment',         avgName, ...
             'TimeBands',       [], ...
             'Freqs',           [], ...
             'ClusterFuncTime', 'none', ...
             'Measure',         'power', ...
             'Output',          'average', ...
             'SaveKernel',      0));
        avgPSDFile = bst_process('CallProcess', 'process_tf_norm', avgPSDFile, [], ...
        'normalize', 'relative2020', ...  % Relative power (divide by total power)
        'overwrite', 1);
        avgPSDFile = bst_process('CallProcess', 'process_set_comment', avgPSDFile, [], ...
                'tag',           avgName, ...
                'isindex',       1);
    end
end
end